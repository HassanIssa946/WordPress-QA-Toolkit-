// Load testing with k6 (smoke / load / stress). GET requests only, approval-gated, capped at 50 VUs / 10 minutes,
// never production. Local results describe this machine, not production capacity.
import fs from 'node:fs';
import path from 'node:path';
import { run as runCmd, exists, IS_WIN, truncate } from '../lib/util.mjs';
import { effectiveLimits } from '../lib/safety.mjs';

const CAT = 'scalability';

/** "2m" / "30s" / "1h" / 90 → seconds (null when invalid). */
export function durationSec(v) {
  if (typeof v === 'number') return v > 0 ? v : null;
  const m = String(v || '').trim().match(/^(\d+(?:\.\d+)?)\s*(ms|s|m|h)?$/i);
  if (!m) return null;
  return Math.round(Number(m[1]) * { ms: 0.001, s: 1, m: 60, h: 3600 }[(m[2] || 's').toLowerCase()]);
}

/** k6 stages + totals for a profile. Never above the effective limits (the gate re-checks). */
export function buildProfile(profile, load, limits) {
  // An invalid duration in config is refused (durationSec null), never replaced by a default.
  const ramp = load.rampUp == null ? 30 : durationSec(load.rampUp);
  if (profile === 'smoke') {
    const vus = Math.min(load.smokeVus ?? 2, limits.maxVus), d = durationSec(load.smokeDuration ?? '30s');
    return { profile, vus, durationSec: d, stages: [{ duration: `${d}s`, target: vus }] };
  }
  if (profile === 'load') {
    const vus = Math.min(load.vus, limits.maxVus), hold = load.duration == null ? 120 : durationSec(load.duration);
    return { profile, vus, durationSec: ramp == null || hold == null ? null : ramp + hold + 15, stages: [{ duration: `${ramp}s`, target: vus }, { duration: `${hold}s`, target: vus }, { duration: '15s', target: 0 }] };
  }
  if (profile === 'stress') {
    const top = limits.maxVus, step = durationSec(load.stressStep ?? '1m');
    if (step == null) return { profile, vus: top, durationSec: null, stages: [], stress: true };
    const stages = [0.25, 0.5, 0.75, 1].map((f) => ({ duration: `${step}s`, target: Math.max(1, Math.round(top * f)) }));
    stages.push({ duration: '30s', target: 0 });
    return { profile, vus: top, durationSec: step * 4 + 30, stages, stress: true };
  }
  return null;
}

/** The k6 script: GET only, thresholds on p95 and error rate, summary written as JSON. */
export function k6Script({ urls, stages, p95Ms, errorRate, summaryPath, insecure }) {
  return `// Generated by wpqa-toolkit. GET requests only.
import http from 'k6/http';
import { check, sleep } from 'k6';
export const options = {
  stages: ${JSON.stringify(stages)},
  thresholds: { http_req_duration: ['p(95)<${p95Ms}'], http_req_failed: ['rate<${errorRate}'] },
  insecureSkipTLSVerify: ${insecure ? 'true' : 'false'},
  userAgent: 'wpqa-toolkit-k6 (approved QA load test)',
};
const URLS = ${JSON.stringify(urls)};
export default function () {
  for (const u of URLS) {
    const r = http.get(u, { tags: { name: u } });
    check(r, { 'status < 400': (x) => x.status > 0 && x.status < 400 });
    sleep(1);
  }
}
export function handleSummary(data) { return { ${JSON.stringify(summaryPath)}: JSON.stringify(data) }; }
`;
}

/** k6 summary → numbers the report needs. */
export function readSummary(s) {
  const m = s?.metrics || {};
  const v = (k, f) => m[k]?.values?.[f] ?? m[k]?.[f] ?? null;
  const th = (k) => Object.values(m[k]?.thresholds || {}).every((x) => x.ok !== false);
  return { p95Ms: v('http_req_duration', 'p(95)'), avgMs: v('http_req_duration', 'avg'), errorRate: v('http_req_failed', 'rate'), requests: v('http_reqs', 'count'), rps: v('http_reqs', 'rate'), vusMax: v('vus_max', 'max') ?? v('vus_max', 'value'), p95Ok: th('http_req_duration'), errorsOk: th('http_req_failed') };
}

async function findK6(run) {
  const t = await run.tool('k6');
  if (t.ok) return { cmd: run.cfg.tools.k6, version: t.version };
  const winDefault = 'C:\\Program Files\\k6\\k6.exe';
  if (IS_WIN && exists(winDefault)) return { cmd: winDefault, version: null };
  return null;
}

export default async function scalability(run) {
  const { cfg, flags } = run;
  await run.check({ id: 'scalability.k6', title: 'Load test with k6 (GET only; smoke / load / stress)', category: CAT, tool: 'k6', requires: { url: true } }, async (c) => {
    const profileName = flags.profile || 'load';
    const limits = effectiveLimits(cfg);
    const prof = buildProfile(profileName, cfg.load, limits);
    if (!prof) return c.skip(`unknown --profile "${profileName}" (use smoke, load or stress)`);
    if (!prof.durationSec) return c.skip('invalid load duration in config (use e.g. "2m" or "30s")');
    const base = cfg.site.url.replace(/\/$/, '');
    if (!(await c.requireApproval('load', base, { vus: prof.vus, durationSec: prof.durationSec, stress: !!prof.stress }))) return;
    const k6 = run.k6 ? { cmd: 'k6' } : await findK6(run);
    if (!k6) return c.skip('k6 not installed', 'Install k6 (winget install GrafanaLabs.k6) and restart the terminal.');
    const urls = (cfg.load.paths || cfg.site.pages || ['/']).map((p) => new URL(p, base + '/').href);
    const dir = run.artifactDir('k6');
    const summaryPath = path.join(dir, 'summary.json');
    const script = path.join(dir, 'script.js');
    fs.writeFileSync(script, k6Script({ urls, stages: prof.stages, p95Ms: cfg.load.p95Ms, errorRate: cfg.load.errorRate, summaryPath: summaryPath.split(path.sep).join('/'), insecure: cfg.site.environment !== 'production' }));
    c.artifact(script, 'k6 script');
    c.scope(urls);
    const r = run.k6
      ? await run.k6({ script, summaryPath, prof })
      : await runCmd(Array.isArray(k6.cmd) ? k6.cmd[0] : k6.cmd, ['run', '--quiet', '--no-color', script], { timeoutMs: (prof.durationSec + 120) * 1000 });
    let summary = null;
    try { summary = JSON.parse(fs.readFileSync(summaryPath, 'utf8')); } catch { /* none */ }
    if (!summary) return c.toolError('k6 run', r, 'no summary produced');
    c.artifact(summaryPath, 'k6 summary');
    const s = readSummary(summary);
    const label = cfg.site.environment === 'production' ? '' : ' — this machine, not production capacity';
    c.stats = { profile: prof.profile, vus: prof.vus, durationSec: prof.durationSec, ...s };
    c.note(`${prof.profile}: ${prof.vus} VUs, ${prof.durationSec}s, ${s.requests ?? '?'} requests, p95 ${s.p95Ms != null ? Math.round(s.p95Ms) : '?'} ms, errors ${s.errorRate != null ? (s.errorRate * 100).toFixed(2) : '?'}%${label}`);
    if (!s.p95Ok) c.finding({ severity: 'medium', rule: 'load.p95', title: `p95 response time ${Math.round(s.p95Ms)} ms > ${cfg.load.p95Ms} ms at ${prof.vus} VUs (${prof.profile})${label}`, url: base, fingerprintExtra: prof.profile, recommendation: 'Look at page caching, slow queries (Query Monitor) and PHP workers. Local numbers only show relative changes.' });
    if (!s.errorsOk) c.finding({ severity: 'high', rule: 'load.errors', title: `${(s.errorRate * 100).toFixed(2)}% of requests failed at ${prof.vus} VUs (${prof.profile}; limit ${(cfg.load.errorRate * 100).toFixed(1)}%)${label}`, url: base, fingerprintExtra: prof.profile, recommendation: 'Check the PHP/web server error log for this period (timeouts, 502/503, database connections).' });
    if (r?.code && r.code !== 0 && r.code !== 99) c.note(`k6 exited with code ${r.code}: ${truncate((r.stderr || '').trim().split('\n').pop() || '', 160)}`);
    run.sections.push({ id: 'load', title: `Load test (k6, ${prof.profile})`, lines: [`${prof.vus} VUs, ${prof.durationSec}s, GET only on ${urls.length} URL(s). ${label ? 'Local result: it measures this machine, not production capacity.' : ''}`, '', `| Requests | Req/s | p95 | Avg | Errors |`, '|---:|---:|---:|---:|---:|', `| ${s.requests ?? '—'} | ${s.rps != null ? s.rps.toFixed(1) : '—'} | ${s.p95Ms != null ? Math.round(s.p95Ms) + ' ms' : '—'} | ${s.avgMs != null ? Math.round(s.avgMs) + ' ms' : '—'} | ${s.errorRate != null ? (s.errorRate * 100).toFixed(2) + '%' : '—'} |`], data: { profile: prof, ...s } });
  });
}
