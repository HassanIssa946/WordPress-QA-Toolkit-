// PHP output hygiene, tool command building, LocalWP environment, page seeding.
import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { cleanPhpOutput, toolCommand, withPhpFlags, toolEnv, pathKey } from '../lib/util.mjs';
import { parseEnvrc, localWpTools, localSiteInfo } from '../lib/localwp.mjs';
import { extractLocs, seedPages } from '../lib/pages.mjs';
import { tempDir } from './helpers.mjs';

const IMAGICK = "Warning: PHP Startup: Unable to load dynamic library 'php_imagick.dll' (tried: C:/php/ext\\php_imagick.dll (The specified module could not be found)) in Unknown on line 0";

describe('PHP diagnostics never reach parsed output', () => {
  test('startup warning before a value is removed (wp option get blog_public)', () => {
    const r = cleanPhpOutput(`\n${IMAGICK}\n0\n`);
    assert.equal(r.stdout.trim(), '0');
    assert.deepEqual(r.diagnostics, [IMAGICK]);
  });
  test('notices around JSON are removed and the JSON stays intact', () => {
    const json = '[{"name":"polylang","status":"active"}]';
    const r = cleanPhpOutput(`PHP Notice:  Undefined index: x in C:\\site\\wp-content\\plugins\\a.php on line 12\n${json}\nDeprecated: Creation of dynamic property in /x.php on line 3`);
    assert.equal(r.stdout.trim(), json);
    assert.equal(r.diagnostics.length, 2);
  });
  test('ordinary output (including JSON strings mentioning warnings) is untouched', () => {
    const text = '{\n  "message": "Warning: x on line 2"\n}';
    assert.equal(cleanPhpOutput(text).stdout, text);
  });
  test('php commands get -d display_errors=stderr, once, right after the binary', () => {
    assert.deepEqual(toolCommand('C:/php/php.exe'), ['C:/php/php.exe', '-d', 'display_errors=stderr']);
    assert.deepEqual(toolCommand(['C:/php/php.exe', 'C:/wp-cli.phar']), ['C:/php/php.exe', '-d', 'display_errors=stderr', 'C:/wp-cli.phar']);
    assert.deepEqual(toolCommand('C:/wp-cli.phar', 'php'), ['php', '-d', 'display_errors=stderr', 'C:/wp-cli.phar']);
    assert.deepEqual(withPhpFlags(withPhpFlags(['php', 'x'])), ['php', '-d', 'display_errors=stderr', 'x']);
    assert.deepEqual(toolCommand('wp'), ['wp']);
    assert.deepEqual(toolCommand('semgrep'), ['semgrep']);
  });
});

describe('tool environment', () => {
  test('pathPrepend goes in front of PATH under the key this process uses', () => {
    const env = toolEnv({ env: { PHPRC: 'C:/conf' }, pathPrepend: ['C:/magick'] });
    const key = pathKey();
    assert.equal(env.PHPRC, 'C:/conf');
    assert.ok(env[key].startsWith(path.normalize('C:/magick') + path.delimiter));
    assert.equal(Object.keys(env).filter((k) => k.toUpperCase() === 'PATH').length, 1);
  });
  test('no pathPrepend → PATH untouched', () => {
    assert.deepEqual(toolEnv({ env: { A: '1' } }), { A: '1' });
  });
});

describe('LocalWP', () => {
  const envrc = [
    '# This file is auto-generated by Local when the site starts.',
    'export MYSQL_HOME="C:/Local/run/abc/conf/mysql"',
    'export PHPRC="C:/Local/run/abc/conf/php"',
    'export WP_CLI_CONFIG_PATH="C:/Local/wp-cli/config.yaml"',
    'export PATH="C:/Local/mysql/bin:$PATH"',
    'export PATH="C:/Local/php/bin/win64:$PATH"',
    'export PATH="C:/Local/wp-cli/win32:$PATH"',
    'export PATH="C:\\Local\\php\\bin\\win64\\ImageMagick:$PATH"',
  ].join('\n');

  test('parseEnvrc keeps Windows drive letters and PATH order', () => {
    const { vars, pathPrepend } = parseEnvrc(envrc);
    assert.equal(vars.PHPRC, 'C:/Local/run/abc/conf/php');
    assert.deepEqual(pathPrepend, ['C:\\Local\\php\\bin\\win64\\ImageMagick', 'C:/Local/wp-cli/win32', 'C:/Local/php/bin/win64', 'C:/Local/mysql/bin']);
  });

  test('localWpTools builds php / wp-cli.phar / env / pathPrepend from a site folder', () => {
    const root = tempDir();
    const phpDir = path.join(root, 'lightning-services', 'php-8.2.29+0', 'bin', 'win64');
    const wpcli = path.join(root, 'bin', 'wp-cli');
    fs.mkdirSync(path.join(phpDir, 'ImageMagick'), { recursive: true });
    fs.mkdirSync(path.join(wpcli, 'win32'), { recursive: true });
    fs.writeFileSync(path.join(phpDir, process.platform === 'win32' ? 'php.exe' : 'php'), '');
    fs.writeFileSync(path.join(wpcli, 'wp-cli.phar'), '');
    const site = path.join(root, 'site');
    fs.mkdirSync(path.join(site, 'app'), { recursive: true });
    fs.writeFileSync(path.join(site, 'app', '.envrc'), [
      `export PHPRC="${root}/run/conf/php"`,
      `export PATH="${phpDir}:$PATH"`,
      `export PATH="${path.join(wpcli, 'win32')}:$PATH"`,
      `export PATH="${path.join(phpDir, 'ImageMagick')}:$PATH"`,
    ].join('\n'));
    const t = localWpTools(site);
    const fwd = (p) => p.split(path.sep).join('/');
    assert.equal(t.php, fwd(path.join(phpDir, process.platform === 'win32' ? 'php.exe' : 'php')));
    assert.deepEqual(t.wp, [t.php, fwd(path.join(wpcli, 'wp-cli.phar'))]);
    assert.equal(t.env.PHPRC, fwd(`${root}/run/conf/php`));
    assert.deepEqual(t.pathPrepend, [fwd(path.join(phpDir, 'ImageMagick'))]);
  });

  test('localWpTools returns null when the site has no .envrc (never started)', () => {
    assert.equal(localWpTools(tempDir()), null);
  });

  test('localSiteInfo finds the real domain in sites.json (my-shop.local, not myshop.local)', () => {
    const json = { sbHUJ: { name: 'My Shop', path: path.join(path.sep, 'Sites', 'my-shop'), domain: 'my-shop.local' } };
    assert.deepEqual(localSiteInfo(path.join(path.sep, 'Sites', 'my-shop'), json), { id: 'sbHUJ', name: 'My Shop', domain: 'my-shop.local' });
    assert.equal(localSiteInfo(path.join(path.sep, 'Sites', 'other'), json), null);
  });
});

describe('init page seeding', () => {
  const site = 'http://site.local';
  const mockFetch = (routes) => async (url) => {
    const p = new URL(url).pathname + new URL(url).search;
    const body = routes[p];
    return body === undefined ? { ok: true, status: 404, text: '' } : { ok: true, status: 200, text: body };
  };
  const index = `<?xml version="1.0"?><sitemapindex><sitemap><loc>${site}/post-sitemap.xml</loc></sitemap><sitemap><loc>${site}/page-sitemap.xml</loc></sitemap></sitemapindex>`;
  const pagesXml = `<urlset><url><loc>${site}/</loc></url><url><loc>${site}/about-us/</loc></url><url><loc><![CDATA[${site}/contact-us/]]></loc></url><url><loc>https://other.host/x/</loc></url></urlset>`;

  test('extractLocs handles CDATA and entities', () => {
    assert.deepEqual(extractLocs('<loc><![CDATA[http://a/x?b=1&amp;c=2]]></loc><loc> http://a/y </loc>'), ['http://a/x?b=1&c=2', 'http://a/y']);
  });
  test('Yoast/Rank Math: core sitemap 404 → sitemap_index.xml → page-sitemap.xml', async () => {
    const r = await seedPages(site, { fetch: mockFetch({ '/sitemap_index.xml': index, '/page-sitemap.xml': pagesXml }) });
    assert.deepEqual(r.pages, ['/', '/about-us/', '/contact-us/']);
    assert.equal(r.source, `${site}/page-sitemap.xml`);
  });
  test('core sitemap used when present', async () => {
    const r = await seedPages(site, { fetch: mockFetch({ '/wp-sitemap-pages-1.xml': pagesXml }) });
    assert.equal(r.source, 'wp-sitemap-pages-1.xml');
  });
  test('falls back to the REST API, then to "/"', async () => {
    const rest = await seedPages(site, { fetch: mockFetch({ '/wp-json/wp/v2/pages?per_page=20&_fields=link&orderby=menu_order&order=asc': JSON.stringify([{ link: `${site}/team/` }]) }) });
    assert.deepEqual(rest.pages, ['/', '/team/']);
    const none = await seedPages(site, { fetch: mockFetch({}) });
    assert.deepEqual(none, { pages: ['/'], source: 'none' });
  });
});
